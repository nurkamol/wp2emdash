/**
 * The kit workspace for the seeded WordPress: a site folder under a temporary sites dir (never the repo's sites/),
 * made with the kit's own `initSite`, then configured for what the seed contains (WooCommerce catalogue mode, Polylang,
 * the forms) the way an operator would: kit.config.ts, overrides.ts, ACCESS.md ticks, .env and the plugin export.
 */
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { initSite } from "../../src/commands/init.js";
import { sitePaths } from "../../src/core/paths.js";

export const E2E_SLUG = "harbor-lane-e2e";
/** A reserved name (RFC 2606): canonical URLs point here; nothing ever resolves or deploys to it. */
export const E2E_PRODUCTION_URL = "https://harbor-lane.example";

/** Environment variables that could point the kit at a real Cloudflare account or EmDash site: the runner refuses them. */
export function forbiddenEnv(e: NodeJS.ProcessEnv): string[] {
	return Object.keys(e).filter((k) => /^(CLOUDFLARE_|CF_API|EMDASH_TOKEN|EMDASH_WP_MIGRATION_KEY)/.test(k) && !!e[k]);
}

/** Kit .env keys blanked in the e2e site's .env (a site .env value wins over the kit's, src/extract/credentials.ts). */
export const KIT_ENV_BLANK = /^(CLOUDFLARE_|CF_|EMDASH_TOKEN|EMDASH_WP_MIGRATION_KEY)/;

export interface E2eSiteOptions {
	sitesDir: string;
	/** The seeded WordPress, e.g. http://localhost:8080 */
	wpUrl: string;
	/** WordPress application password (from the seed); written to the site's .env only. */
	appPassword: string;
	appUser?: string;
	/** e2e/wordpress/.work: plugin exports and Elementor options written by the seed. */
	workDir?: string;
	/**
	 * Keep every kit default. Off (default): the two features that add the remote-only Workers AI binding (SEO panel
	 * fix-it drafts, Media alt suggestions) are switched off, so `astro dev` can run without a Cloudflare account.
	 */
	fullDefaults?: boolean;
}

export function e2eConfigText(o: Pick<E2eSiteOptions, "wpUrl" | "fullDefaults">): string {
	const ai = o.fullDefaults
		? ""
		: `	// Workers AI bindings are remote-only and CI has no Cloudflare account by design (docs/e2e.md).
	seo: { panel: false },
	media: { aiAlt: false },
`;
	return `// Generated by e2e/lib/site.ts for the synthetic WordPress end-to-end test. Not a client site.
export default {
	slug: ${JSON.stringify(E2E_SLUG)},
	name: "Harbor Lane Pottery (e2e)",
	source: {
		url: ${JSON.stringify(o.wpUrl)},
	},
	target: {
		kind: "emdash",
		productionUrl: ${JSON.stringify(E2E_PRODUCTION_URL)},
		template: "cloudflare:marketing",
		trailingSlash: "preserve",
		canonicalHost: "apex",
	},
	email: {
		provider: "emdash",
		to: ["owner@example.test"],
		stagingTo: ["test@example.test"],
	},
	shop: {
		mode: "catalogue",
		checkout: "contact",
		currency: "USD",
		contactPath: "/contact/",
	},
${ai}	sensitiveData: false,
};
`;
}

export const E2E_OVERRIDES = `// Generated by e2e/lib/site.ts: decisions for the synthetic e2e site (reasons in decisions.md).
export default {
	routes: {},
	elements: {},
	integrations: {},
	media: { external: {} },
	redirects: { source: "none" },
	approvedLegacy: [],
	contentTypes: {},
	taxonomies: {},
	wpUrls: {},
	gone: {},
};
`;

/** Ticks every box in the given ACCESS.md sections (the synthetic site has no owner, backup or DNS to check). */
export function tickAccess(markdown: string, sections: string[]): string {
	let section = "";
	return markdown
		.split("\n")
		.map((line) => {
			const h = /^##\s+(.+?)\s*$/.exec(line);
			if (h?.[1]) section = h[1].toLowerCase();
			return sections.some((s) => s.toLowerCase() === section) ? line.replace(/^(\s*[-*]\s+)\[ \]/, "$1[x]") : line;
		})
		.join("\n");
}

export interface E2eSite {
	slug: string;
	root: string;
	sitesDir: string;
}

export function createE2eSite(o: E2eSiteOptions): E2eSite {
	mkdirSync(o.sitesDir, { recursive: true });
	const p = sitePaths(E2E_SLUG, o.sitesDir);
	initSite({ slug: E2E_SLUG, name: "Harbor Lane Pottery (e2e)", sourceUrl: o.wpUrl, productionUrl: E2E_PRODUCTION_URL, sensitiveData: false }, o.sitesDir);
	writeFileSync(p.config, e2eConfigText(o));
	writeFileSync(p.overrides, E2E_OVERRIDES);
	writeFileSync(p.access, tickAccess(readFileSync(p.access, "utf8"), ["Before audit", "Before extract"]));
	const today = new Date().toISOString().slice(0, 10);
	writeFileSync(
		p.decisions,
		`${readFileSync(p.decisions, "utf8")}| ${today} | init | Synthetic end-to-end site: ACCESS.md "Before audit"/"Before extract" ticked by e2e/lib/site.ts | Throwaway WordPress in Docker, no owner, backup or DNS | e2e/run.ts |\n| ${today} | extract | No redirects (overrides.ts redirects.source "none") | Fresh WordPress install | e2e/run.ts |\n`,
	);
	writeFileSync(join(p.root, ".env"), `WP_APP_USER=${o.appUser ?? "admin"}\nWP_APP_PASSWORD=${o.appPassword}\n`, { mode: 0o600 });
	if (o.workDir) {
		const cf7 = join(o.workDir, "exports", "contact-form-7.xml");
		if (existsSync(cf7)) {
			mkdirSync(join(p.raw, "plugin-exports"), { recursive: true });
			copyFileSync(cf7, join(p.raw, "plugin-exports", "contact-form-7.xml"));
		}
		const el = join(o.workDir, "elementor-options.json");
		if (existsSync(el)) copyFileSync(el, join(p.raw, "elementor-options.json"));
	}
	return { slug: E2E_SLUG, root: p.root, sitesDir: o.sitesDir };
}
