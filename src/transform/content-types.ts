/**
 * Content inventory: every non-empty post type, every taxonomy with terms in use and the authors with published
 * content, and what the migration does with each. Nothing the extract found may disappear without a line here: a
 * type the transform does not migrate stays "undecided" (transform gate `content-types-handled` fails) until
 * overrides.ts records a decision with the owner's reason (`contentTypes`, `taxonomies`, `authors`).
 */
import type { Overrides } from "../config/overrides.js";

/** Types the transform migrates (or uses) on its own. `post` is partly: only builder (WPBakery/Bricks/Elementor) posts. */
export const HANDLED_TYPES: Record<string, string> = {
	page: "pages",
	popup: "popups (Popup Maker)",
	popup_theme: "popup styling, rebuilt from the design capture",
	salient_g_sections: "site parts (Salient global sections)",
	bricks_template: "site parts and popups (Bricks templates)",
	elementor_library: "site parts, popups, inlined templates and the Kit (Elementor library)",
	wp_block: "inlined where referenced (reusable blocks)",
	wp_navigation: "classic menus are used",
	rank_math_schema: "JSON-LD regenerated by the starter",
};

/** Configuration and builder libraries: listed, never public content of their own. */
export const INTERNAL_TYPES: Record<string, string> = {
	"acf-field-group": "ACF configuration",
	"acf-field": "ACF configuration",
	"acf-post-type": "ACF configuration",
	"acf-taxonomy": "ACF configuration",
	"acf-ui-options-page": "ACF configuration",
	et_pb_layout: "builder template library (used layouts are inlined)",
	vc_grid_item: "WPBakery grid templates",
	templately_library: "builder template library",
	pum_cta: "Popup Maker call-to-action settings",
	wpcf7_contact_form: "form definition (forms are checked by the extract `forms` gate)",
	wpforms: "form definition (forms are checked by the extract `forms` gate)",
	shop_order: "store orders (customer data, never migrated)",
	shop_order_refund: "store orders (customer data, never migrated)",
	shop_coupon: "store configuration",
	shop_webhook: "store configuration",
	product_variation: "listed with `product`",
};

/** Taxonomies that classify configuration, not content. */
export const INTERNAL_TAXONOMIES = new Set(["nav_menu", "link_category", "post_format", "wp_theme", "wp_template_part_area", "wp_pattern_category", "template_tag", "template_bundle", "elementor_library_type", "elementor_library_category", "product_type", "product_visibility", "product_shipping_class", "nt_wmc_folder", "filebird_folder", "media_folder", "rml_folder"]);

export type InventoryStatus = "migrated" | "decided" | "internal" | "undecided";

export interface InventoryRow {
	group: "type" | "taxonomy" | "authors";
	name: string;
	/** Entries (types), terms in use (taxonomies), authors with content (authors). */
	total: number;
	published: number;
	/** Entries the transform migrates without a decision. */
	handled: number;
	status: InventoryStatus;
	note: string;
	decision?: { as: string; reason: string };
	samples: string[];
}

export interface InventoryInput {
	/** Per post type: every entry's status and (for posts) whether the transform migrates it. */
	types: { name: string; entries: { status: string; handled: boolean }[] }[];
	taxonomies: { name: string; terms: { count: number }[] }[];
	authors: { name: string; posts: number }[];
	/** Public URLs from the audit by post type / taxonomy (samples for the report). */
	samples: { types: Record<string, string[]>; taxonomies: Record<string, string[]>; authors: string[] };
	attachments?: number;
	overrides: Pick<Overrides, "contentTypes" | "taxonomies" | "authors">;
	/**
	 * What the blog migrates (src/transform/blog.ts): post types → note (`post` → "posts collection"), WordPress
	 * taxonomies → note, and whether the authors become bylines.
	 */
	blog?: { types: Record<string, string>; taxonomies: Record<string, string>; authors?: string };
}

export function contentInventory(input: InventoryInput): InventoryRow[] {
	const rows: InventoryRow[] = [];
	const live = (s: string) => s === "publish" || s === "future" || s === "private";
	for (const t of input.types) {
		if (!t.entries.length) continue;
		const published = t.entries.filter((e) => e.status === "publish").length;
		const handled = t.entries.filter((e) => e.handled).length;
		const decision = input.overrides.contentTypes[t.name];
		const samples = (input.samples.types[t.name] ?? []).slice(0, 3);
		const base = { group: "type" as const, name: t.name, total: t.entries.length, published, handled, samples };
		if (decision) rows.push({ ...base, status: "decided", decision, note: decision.as === "skip" ? "not migrated (owner decision)" : "migrated as pages at their WordPress address" });
		else if (input.blog?.types[t.name]) rows.push({ ...base, status: "migrated", note: input.blog.types[t.name] as string });
		else if (INTERNAL_TYPES[t.name]) rows.push({ ...base, status: "internal", note: INTERNAL_TYPES[t.name] as string });
		else if (HANDLED_TYPES[t.name]) rows.push({ ...base, status: "migrated", note: HANDLED_TYPES[t.name] as string });
		else {
			const open = t.entries.filter((e) => !e.handled && live(e.status)).length;
			const note = t.name === "post" ? (open ? `${open} Gutenberg/classic post(s) have no posts collection yet${handled ? `; ${handled} builder post(s) migrated as pages` : ""}` : "builder posts migrated as pages") : open ? "no collection for this type" : "no published entries";
			rows.push({ ...base, status: open ? "undecided" : "migrated", note });
		}
	}
	if (input.attachments) rows.push({ group: "type", name: "attachment", total: input.attachments, published: input.attachments, handled: input.attachments, status: "migrated", note: "files used by pages are uploaded; attachment pages follow the WordPress-URL rules (parent page, file or home)", samples: [] });
	for (const tx of input.taxonomies) {
		const used = tx.terms.filter((t) => t.count > 0).length;
		if (!used) continue;
		const decision = input.overrides.taxonomies[tx.name];
		const base = { group: "taxonomy" as const, name: tx.name, total: used, published: used, handled: 0, samples: (input.samples.taxonomies[tx.name] ?? []).slice(0, 3) };
		if (decision) rows.push({ ...base, status: "decided", decision, note: "archives not rebuilt (owner decision); their URLs follow the WordPress-URL rules" });
		else if (input.blog?.taxonomies[tx.name]) rows.push({ ...base, status: "migrated", handled: used, note: input.blog.taxonomies[tx.name] as string });
		else if (INTERNAL_TAXONOMIES.has(tx.name)) rows.push({ ...base, status: "internal", note: "classifies configuration, not content" });
		else rows.push({ ...base, status: "undecided", note: "terms in use: no taxonomy is migrated yet" });
	}
	const writers = input.authors.filter((a) => a.posts > 0);
	if (writers.length) {
		const decision = input.overrides.authors;
		const base = { group: "authors" as const, name: writers.map((a) => a.name).join(", "), total: writers.length, published: writers.reduce((n, a) => n + a.posts, 0), handled: 0, samples: input.samples.authors.slice(0, 3) };
		rows.push(decision ? { ...base, status: "decided", decision, note: "no bylines or author pages (owner decision); author URLs follow the WordPress-URL rules" } : input.blog?.authors ? { ...base, status: "migrated", handled: writers.length, note: input.blog.authors } : { ...base, status: "undecided", note: "authors with published posts: bylines are not migrated yet" });
	}
	return rows;
}

export function inventoryDetail(rows: InventoryRow[]): string {
	const open = rows.filter((r) => r.status === "undecided");
	if (open.length) return `${open.length} need a decision (coverage report → Content types; overrides.ts contentTypes / taxonomies / authors): ${open.map((r) => `${r.group === "type" ? "" : `${r.group} `}${r.name} (${r.total})`).join(", ")}`;
	const by = (s: InventoryStatus) => rows.filter((r) => r.status === s).map((r) => r.name);
	return [`migrated: ${by("migrated").join(", ") || "—"}`, by("decided").length ? `decided: ${by("decided").join(", ")}` : "", by("internal").length ? `internal: ${by("internal").join(", ")}` : ""].filter(Boolean).join("; ");
}

export function inventoryReport(rows: InventoryRow[]): string[] {
	if (!rows.length) return [];
	const L = ["", "## Content types", "", "Every post type with entries, every taxonomy with terms in use and the authors with published posts. **undecided** blocks the gate: record a decision with the owner's reason in `overrides.ts` (`contentTypes: { <type>: { as: \"skip\" | \"pages\", reason } }`, `taxonomies`, `authors`).", "", "| Kind | Name | Count | Published | Status | What happens | Sample URLs |", "|---|---|---|---|---|---|---|"];
	const esc = (s: string) => s.replace(/\|/g, "\\|");
	for (const r of rows) L.push(`| ${r.group} | ${esc(r.name)} | ${r.total} | ${r.published} | ${r.status === "undecided" ? "❌ undecided" : r.status} | ${esc(r.decision ? `${r.note}: ${r.decision.reason}` : r.note)} | ${r.samples.map((s) => `\`${s}\``).join(" ") || "—"} |`);
	return L;
}
