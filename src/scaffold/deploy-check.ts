/**
 * scripts/deploy-check.mjs in the generated project: runs after `wrangler deploy` (and the warm-up) and checks the
 * address it deployed to like a visitor would. When something is broken it rolls the Worker back to the version that
 * was live before (`wrangler rollback`) and fails the deploy, so a bad build is never left serving visitors.
 *
 * Why: a build once reached production without its body font (the Google Fonts download dropped a family); nothing
 * failed, visitors saw the fallback font until it was noticed by eye. The checks are the things a build can lose
 * without any error: pages, the site's fonts, its stylesheets and scripts, the hero picture, the main content.
 *
 * What it reads: src/site.config.json (fonts the site uses), the live sitemap and pages. No browser (CI has none):
 * HTML and CSS are checked as text. Wrangler is called in the same directory right after the deploy, so it targets
 * the same Worker the deploy did (the staging build's redirected config included) — no names baked in.
 *
 * Rollback and the database: `emdash migrate` runs before `wrangler deploy`; EmDash's migrations add tables and
 * columns, which the previous version ignores, so rolling the code back is safe. Turn rollback off with
 * kit.config `performance.rollback: false` (the check still fails the deploy) or for one run with DEPLOY_ROLLBACK=0.
 */
import type { PerfConfig } from "./perf.js";

/** Appends the check to every deploy script (after the warm-up when there is one). */
export function withDeployCheck(scripts: Record<string, string>, urls: { staging?: string; production?: string }, perf: PerfConfig): Record<string, string> {
	if (!perf.deployCheck) return scripts;
	return Object.fromEntries(
		Object.entries(scripts).map(([k, v]) => {
			const url = /staging/.test(k) ? urls.staging : urls.production;
			if (!/\bwrangler (?:versions )?deploy\b/.test(v) || !url || v.includes("scripts/deploy-check.mjs")) return [k, v];
			return [k, `${v} && node scripts/deploy-check.mjs ${url.replace(/\/$/, "")}${perf.rollback ? "" : " --no-rollback"}`];
		}),
	);
}

export const DEPLOY_CHECK_SCRIPT = `#!/usr/bin/env node
// Generated by wp2emdash scaffold (src/scaffold/deploy-check.ts). After a deploy: checks the live site like a visitor
// (every sitemap page answers 200, the site's fonts are in its stylesheets, stylesheets/scripts load, the hero picture
// loads, pages have their main content and footer). On a failure it rolls the Worker back to the version that was live
// before and exits 1, so the deploy is marked failed.
// Usage: node scripts/deploy-check.mjs https://example.com [--no-rollback]   (DEPLOY_ROLLBACK=0 also skips rollback)
import { spawnSync } from "node:child_process";
import { readFileSync } from "node:fs";

const base = (process.argv[2] ?? "").replace(/\\/$/, "");
const rollbackOn = !process.argv.includes("--no-rollback") && process.env.DEPLOY_ROLLBACK !== "0";
if (!/^https?:\\/\\//.test(base)) {
	console.log("deploy check skipped: no site address given");
	process.exit(0);
}
const origin = new URL(base).origin;
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const problems = [];
const fail = (msg) => problems.push(msg);
const get = async (url, tries = 3) => {
	let last;
	for (let i = 0; i < tries; i++) {
		try {
			const res = await fetch(url, { redirect: "manual", headers: { "user-agent": "site-deploy-check (+deploy)" } });
			const type = res.headers.get("content-type") ?? "";
			const body = /text|json|xml|css|javascript/.test(type) ? await res.text() : (await res.arrayBuffer(), "");
			last = { status: res.status, type, body, location: res.headers.get("location") };
			if (res.status < 500 && res.status !== 0) return last;
		} catch (e) {
			last = { status: 0, type: "", body: "", error: String(e?.message ?? e) };
		}
		await sleep(1500 * (i + 1));
	}
	return last;
};
let site = {};
try {
	site = JSON.parse(readFileSync(new URL("../src/site.config.json", import.meta.url), "utf8"));
} catch {}

// 1. Pages: every sitemap URL answers 200 (a redirect is fine), with a <title>, <main> content and the footer.
const locs = (xml) => [...xml.matchAll(/<loc>\\s*([^<\\s]+)\\s*<\\/loc>/g)].map((m) => m[1].replace(/&amp;/g, "&"));
const local = (u) => {
	try {
		const x = new URL(u, origin);
		return origin + x.pathname + x.search;
	} catch {
		return undefined;
	}
};
const index = await get(origin + "/sitemap.xml");
const urls = new Set([origin + "/"]);
if (index?.status === 200) {
	for (const loc of locs(index.body).map(local).filter(Boolean)) {
		if (/\\.xml$/.test(new URL(loc).pathname)) {
			const part = await get(loc);
			for (const u of locs(part?.body ?? "").map(local).filter(Boolean)) urls.add(u);
		} else urls.add(loc);
	}
} else fail("sitemap.xml answered " + (index?.status || index?.error));
const pages = new Map();
const list = [...urls].slice(0, 300);
for (let i = 0; i < list.length; i += 4)
	await Promise.all(
		list.slice(i, i + 4).map(async (u) => {
			const r = await get(u);
			pages.set(u, r);
			const path = new URL(u).pathname;
			if (!r || (r.status !== 200 && !(r.status >= 300 && r.status < 400))) return fail(path + " answered " + (r?.status || r?.error));
			if (r.status !== 200) return;
			if (!/<title>[^<]+<\\/title>/i.test(r.body)) fail(path + ": no <title>");
			const main = /<main[\\s>][\\s\\S]*?<\\/main>/i.exec(r.body)?.[0] ?? "";
			if (main.replace(/<script[\\s\\S]*?<\\/script>|<style[\\s\\S]*?<\\/style>|<[^>]+>/g, " ").replace(/\\s+/g, " ").trim().length === 0 && !/<img|<video|<iframe|<picture|class="embed/i.test(main)) fail(path + ": the main content is empty");
			if (!/<footer[\\s>]/i.test(r.body)) fail(path + ": no footer");
		}),
	);

// 2. Home page assets: every stylesheet and script it links loads; the hero picture (fetchpriority=high) loads.
const home = pages.get(origin + "/");
const css = [];
if (home?.status === 200) {
	const attr = (tag, name) => new RegExp(name + '="([^"]+)"', "i").exec(tag)?.[1]?.replace(/&amp;/g, "&");
	const assets = new Set();
	for (const m of home.body.matchAll(/<link\\b[^>]*>/gi)) if (/rel="stylesheet"/i.test(m[0])) assets.add(attr(m[0], "href"));
	for (const m of home.body.matchAll(/<script\\b[^>]*\\bsrc="[^"]+"[^>]*>/gi)) assets.add(attr(m[0], "src"));
	for (const a of [...assets].filter(Boolean)) {
		const u = new URL(a, origin);
		if (u.origin !== origin) continue;
		const r = await get(u.href);
		if (r?.status !== 200) fail("asset " + u.pathname + " answered " + (r?.status || r?.error));
		else if (/css/.test(r.type) || u.pathname.endsWith(".css")) css.push(r.body);
	}
	// Inline <style> blocks count as stylesheets too.
	for (const m of home.body.matchAll(/<style[^>]*>([\\s\\S]*?)<\\/style>/gi)) css.push(m[1]);
	const hero = [...home.body.matchAll(/<img\\b[^>]*>/gi)].map((m) => m[0]).find((t) => /fetchpriority="high"/i.test(t));
	if (hero) {
		const src = attr(hero, "src");
		const r = src ? await get(new URL(src, origin).href) : undefined;
		if (!r || r.status !== 200 || !/^image\\//.test(r.type)) fail("hero picture " + (src ?? "(no src)") + " answered " + (r?.status || r?.error || "nothing") + (r?.type ? " (" + r.type + ")" : ""));
	}
} else fail("home page not checked (it did not load)");

// 3. Fonts: every family the site's text uses is defined (self-hosted @font-face) or linked from Google Fonts.
const fonts = site.fonts ?? {};
const generic = /^(system-ui|sans-serif|serif|monospace|-apple-system|arial|helvetica|georgia|times)/i;
const families = [...new Set([fonts.body, fonts.display].filter((f) => typeof f === "string" && f && !generic.test(f)))];
if (home?.status === 200 && families.length) {
	const allCss = css.join("\\n");
	const defined = new Set([...allCss.matchAll(/@font-face\\s*\\{[^}]*?font-family:\\s*["']?([^;"'}]+)["']?/gi)].map((m) => m[1].trim().toLowerCase()));
	const google = [...home.body.matchAll(/https:\\/\\/fonts\\.googleapis\\.com\\/css2\\?[^"'\\s>]+/g)].map((m) => decodeURIComponent(m[0].replace(/&amp;/g, "&").replace(/\\+/g, " ")).toLowerCase()).join(" ");
	const typekit = /use\\.typekit\\.net\\//.test(home.body);
	for (const f of families) if (!defined.has(f.toLowerCase()) && !google.includes("family=" + f.toLowerCase()) && !typekit) fail("font " + f + " is not in the site's stylesheets (visitors would see a fallback font)");
}

// Report, and roll back on a failure.
console.log("deploy check: " + pages.size + " pages, " + css.length + " stylesheets, fonts " + (families.join(", ") || "none") + " — " + (problems.length ? problems.length + " problem(s)" : "all good"));
for (const p of problems.slice(0, 30)) console.log("  ✖ " + p);
if (!problems.length) process.exit(0);
if (!rollbackOn) {
	console.log("deploy check failed; rollback is off — the new version stays live");
	process.exit(1);
}
const wrangler = (args) => spawnSync("npx", ["--no-install", "wrangler", ...args], { encoding: "utf8", env: process.env });
const listed = wrangler(["deployments", "list", "--json"]);
let previous;
try {
	const ds = JSON.parse(listed.stdout.slice(listed.stdout.indexOf("[")));
	const byTime = ds.sort((a, b) => Date.parse(a.created_on) - Date.parse(b.created_on));
	const current = byTime.at(-1)?.versions?.[0]?.version_id;
	previous = [...byTime].reverse().map((d) => d.versions?.[0]?.version_id).find((v) => v && v !== current);
} catch {}
if (!previous) {
	console.log("deploy check failed; no earlier version to roll back to — the new version stays live");
	process.exit(1);
}
const rb = wrangler(["rollback", previous, "-y", "-m", "deploy check failed: " + problems[0].slice(0, 80)]);
console.log(rb.status === 0 ? "rolled back to " + previous + " (the version live before this deploy)" : "ROLLBACK FAILED (" + (rb.stderr || rb.stdout).trim().split("\\n").slice(-2).join(" ") + ") — the new version is still live, fix or roll back by hand");
process.exit(1);
`;
